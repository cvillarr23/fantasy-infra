#!/usr/bin/env python3
"""Generate the run_log failure alerts, one per alert level, from base/launcher/catalog.yaml.

run_log doesn't store a job's `alert` level, so each rule lists the catalog's job names for its
level, with its `max_attempts`, so a run the watcher will retry doesn't alert. An empty catalog
renders rules that match nothing.
"""
import argparse
import textwrap
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'base/launcher/catalog.yaml'
OUT_DIR = ROOT / 'base/telemetry'
LEVELS = ('critical', 'warning')
# Longer than the 5m rule interval, so a run that finishes between evaluations is still seen.
WINDOW = '10 minutes'

HEADER = """\
# GENERATED by scripts/generate-launcher-alerts.py from base/launcher/catalog.yaml; do not edit.
# One series per job. Fires once per run_log row that ended failure or timeout on its last attempt,
# or was skipped for a reason that needs a person (not a pause, or a skip the chain's own timeout
# or cancel already alerts on). A failure the watcher will still retry doesn't alert. Level `{level}`.
# Runbook: docs/cronjob-alerts.md#launcher-run-failed
"""

CONFIGMAP = """\
apiVersion: v1
kind: ConfigMap
metadata:
  name: fantasy-launcher-run-failed-{level}-alert
  namespace: default
  labels:
    grafana_alert: "1"
data:
  launcher-run-failed-{level}.yaml: |
{rule}"""


# Skips that are expected or already covered by another alert: a pause, a slot a chain covers,
# and the steps of a chain that timed out or was cancelled (the chain alert covers those).
QUIET_SKIPS = ('paused', 'chain_step', 'max_duration', 'chain_ended')


def _load_catalog(path):
    # BaseLoader keeps every scalar a string, like generate-schedules.py: YAML 1.1 would turn
    # `on` or `no` into booleans. An empty value loads as '', so each use below falls back.
    return yaml.load(Path(path).read_text(), Loader=yaml.BaseLoader)


def jobs_at_level(catalog, level):
    """(name, max_attempts) of each job at `level`, sorted by name."""
    defaults = catalog.get('defaults') or {}
    default_level = defaults.get('alert') or 'warning'
    default_attempts = int(defaults.get('max_attempts') or 1)
    found = []
    for name, job in (catalog.get('jobs') or {}).items():
        job = job or {}
        if (job.get('alert') or default_level) == level:
            found.append((name, int(job.get('max_attempts') or default_attempts)))
    return sorted(found)


def _quoted(name):
    return "'" + name.replace("'", "''") + "'"


def _job_attempts(jobs):
    names = ', '.join(_quoted(name) for name, _ in jobs)
    attempts = ', '.join(str(attempts) for _, attempts in jobs)
    return f'unnest(ARRAY[{names}]::text[], ARRAY[{attempts}]::int[]) AS j(job_name, max_attempts)'


# A chain step is only retried while its root is running; once the root ended its failure is final.
_ROOT_ENDED = """r.chain_root_id IS NOT NULL AND r.chain_root_id <> r.id
      AND NOT EXISTS (SELECT 1 FROM run_log root WHERE root.id = r.chain_root_id AND root.status = 'running')"""


def _failed_runs_sql(jobs):
    quiet = ', '.join(f"'{reason}'" for reason in QUIET_SKIPS)
    return f"""\
SELECT r.job_name, COUNT(*)::double precision AS value
FROM run_log r
JOIN {_job_attempts(jobs)} ON j.job_name = r.job_name
WHERE r.finished_at > now() - interval '{WINDOW}'
  AND (
    (
      r.status IN ('failure', 'timeout')
      AND (
        r.attempt >= j.max_attempts
        OR ({_ROOT_ENDED})
      )
    )
    OR (r.status = 'skipped' AND COALESCE(r.end_reason, '') NOT IN ({quiet}))
  )
GROUP BY r.job_name;"""


def _rule(level, jobs):
    sql = _failed_runs_sql(jobs)
    return {
        'apiVersion': 1,
        'groups': [{
            'orgId': 1,
            'name': f'launcher-run-failed-{level}',
            'folder': 'Fantasy',
            'interval': '5m',
            'rules': [{
                'uid': f'launcher-run-failed-{level}',
                'title': f'Launcher run failed ({level} jobs)',
                'condition': 'C',
                'for': '0m',
                'noDataState': 'OK',
                'execErrState': 'Error',
                'labels': {'severity': level},
                'annotations': {
                    'summary': '{{ $labels.job_name }}: {{ $values.B.Value }} run(s) failed, timed out or were skipped in the last 10 minutes.',
                    'runbook_url': 'https://github.com/cvillarr23/fantasy-infra/blob/main/docs/cronjob-alerts.md#launcher-run-failed',
                },
                'data': [
                    {
                        'refId': 'A',
                        'relativeTimeRange': {'from': 600, 'to': 0},
                        'datasourceUid': 'FantasyFootballDB',
                        'model': {'refId': 'A', 'format': 'table', 'rawQuery': True, 'rawSql': sql},
                    },
                    {
                        'refId': 'B',
                        'datasourceUid': '__expr__',
                        'model': {'type': 'reduce', 'expression': 'A', 'reducer': 'last'},
                    },
                    {
                        'refId': 'C',
                        'datasourceUid': '__expr__',
                        'model': {
                            'type': 'threshold',
                            'expression': 'B',
                            'conditions': [{'evaluator': {'type': 'gt', 'params': [0]}}],
                        },
                    },
                ],
            }],
        }],
    }


class _LiteralDumper(yaml.SafeDumper):
    """Writes multi-line strings (the SQL) as readable block scalars."""


def _literal_str(dumper, value):
    style = '|' if '\n' in value else None
    return dumper.represent_scalar('tag:yaml.org,2002:str', value, style=style)


_LiteralDumper.add_representer(str, _literal_str)


def render(catalog_path, level):
    catalog = _load_catalog(catalog_path)
    rule = yaml.dump(_rule(level, jobs_at_level(catalog, level)), Dumper=_LiteralDumper, sort_keys=False, width=1000)
    return HEADER.format(level=level) + CONFIGMAP.format(level=level, rule=textwrap.indent(rule, '    '))


def output_path(level):
    return OUT_DIR / f'launcher-run-failed-{level}-alert.yaml'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if a committed rule is stale')
    args = parser.parse_args()
    stale = []
    for level in LEVELS:
        path, rendered = output_path(level), render(CATALOG, level)
        if args.check:
            if not path.exists() or path.read_text() != rendered:
                stale.append(path.name)
        else:
            path.write_text(rendered)
    if stale:
        parser.exit(1, f'Stale: {", ".join(stale)}; run python3 scripts/generate-launcher-alerts.py\n')


if __name__ == '__main__':
    main()
